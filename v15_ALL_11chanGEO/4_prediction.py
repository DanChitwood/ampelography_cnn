# --- MAIN STRATEGIC PREDICTION LOOP ---
def run_strategic_predictions(input_base_dir, output_base_dir, model_path):
    input_path = Path(input_base_dir)
    output_path = Path(output_base_dir)

    print(f"Scanning input directory: {input_path}")
    all_image_paths_by_subdir = defaultdict(list)
    total_images_found = 0

    for root, _, files in os.walk(input_path):
        current_subdir_rel = Path(root).relative_to(input_path)
        for file in files:
            file_path = Path(root) / file
            if file_path.suffix.lower() in IMAGE_EXTENSIONS:
                all_image_paths_by_subdir[current_subdir_rel].append(file_path)
                total_images_found += 1

    if not all_image_paths_by_subdir:
        print(f"No image files found in '{input_base_dir}' or its subdirectories with extensions: {', '.join(IMAGE_EXTENSIONS)}")
        return

    print(f"Found {total_images_found} image files across {len(all_image_paths_by_subdir)} subdirectories.")

    # Prepare for strategic prediction
    available_images_for_cycle = {
        subdir: list(paths) for subdir, paths in all_image_paths_by_subdir.items()
    }
    
    # Load your model once outside the loop
    model = load_model_for_inference(model_path)
    if model is None:
        print("Model loading failed. Aborting prediction.")
        return

    print("\nStarting strategic prediction...")
    prediction_round = 0
    
    # Track predicted images to ensure 'without replacement' within a cycle for each subdir
    # and to know when to stop if all images are processed globally
    globally_predicted_images = set()

    while True:
        prediction_round += 1
        print(f"\n--- Prediction Round {prediction_round} ---")
        
        made_prediction_this_round = False 
        
        shuffled_subdirs = list(available_images_for_cycle.keys())
        random.shuffle(shuffled_subdirs)

        for subdir_rel_path in shuffled_subdirs:
            current_available_in_cycle = available_images_for_cycle[subdir_rel_path]
            
            # If all images in this subdir for this cycle are processed, reset it
            if not current_available_in_cycle:
                print(f"  - Replenishing images for subfolder: {subdir_rel_path} (Starting new cycle for this subdir)")
                available_images_for_cycle[subdir_rel_path] = list(all_image_paths_by_subdir[subdir_rel_path])
                current_available_in_cycle = available_images_for_cycle[subdir_rel_path] # Update reference

            if current_available_in_cycle:
                # Select a random image from the available ones for this subdir
                selected_image_path = random.choice(current_available_in_cycle)
                
                made_prediction_this_round = True
                
                print(f"  Predicting for subfolder: {subdir_rel_path}")
                print(f"    Selected image: {selected_image_path.name}")

                # 3. Replicate the sub-folder structure in the output directory
                output_subdir = output_path / subdir_rel_path
                output_subdir.mkdir(parents=True, exist_ok=True)

                # Generate a unique stem for the output files (e.g., "image_0" from "image_0.png")
                original_filename_stem = selected_image_path.stem
                
                # Check if outputs already exist for this image in this specific output directory
                # This prevents re-predicting if you stop and restart the script
                mask_output_exists = (output_subdir / f"{original_filename_stem}_mask.png").exists()
                overlay_output_exists = (output_subdir / f"{original_filename_stem}_overlay.png").exists()

                if mask_output_exists and overlay_output_exists:
                    print(f"      Outputs already exist for {selected_image_path.name}. Skipping prediction.")
                    # Still need to remove from available list for this cycle to maintain "without replacement"
                    # and ensure it's not chosen again in this cycle for this subdir.
                    available_images_for_cycle[subdir_rel_path].remove(selected_image_path)
                    globally_predicted_images.add(str(selected_image_path)) # Mark as globally predicted
                    continue # Move to next image/subdir

                # Preprocess, Predict, and Save
                input_tensor, original_padded_pil_img = preprocess_for_prediction(selected_image_path)
                if input_tensor is not None: # Check if preprocessing was successful
                    predicted_mask, predicted_geodesic_map = perform_prediction(model, input_tensor)
                    save_prediction_outputs(output_subdir, original_padded_pil_img, predicted_mask, original_filename_stem)
                    globally_predicted_images.add(str(selected_image_path)) # Mark as globally predicted
                
                # Remove the predicted image from the available list for this cycle for this specific subdir
                available_images_for_cycle[subdir_rel_path].remove(selected_image_path)
            else:
                pass # No images in this subfolder, or all processed in current cycle

        # Termination condition: if no new images were picked in this entire round across all subfolders
        # This implies that all subfolders either finished a cycle or had no images.
        if not made_prediction_this_round and prediction_round > 1:
            print("\nNo new unique images selected across all subfolders in this round. Ending prediction.")
            break
        
        # Optional: Add a maximum number of rounds if you want to limit total runtime
        # if prediction_round >= 20: # Predict up to 20 images from each subfolder per cycle if needed
        #     print("\nReached maximum prediction rounds. Ending prediction.")
        #     break

    print(f"\n--- Prediction Process Completed ---")
    print(f"Total unique images predicted: {len(globally_predicted_images)}")
    print(f"All outputs saved to: {INFERENCE_OUTPUT_DIR}")


