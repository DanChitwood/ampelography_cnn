def load_model_for_inference(model_path):
    """
    Loads your trained PyTorch model and sets it to evaluation mode.
    """
    print(f"Loading model from {model_path}...")
    model = UNet(in_channels=11, num_seg_classes=3, num_geo_channels=1)
    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Model checkpoint not found at: {model_path}\n"
                                "Please update MODEL_PATH to your best saved model.")
    model.load_state_dict(torch.load(model_path, map_location=device))
    model.to(device)
    model.eval() # Set model to evaluation mode
    return model

def preprocess_for_prediction(image_path):
    """
    Loads an image, applies rotation, padding, and creates the 11-channel input tensor.
    Returns the tensor and the original padded PIL image for overlay.
    """
    try:
        original_pil_img = Image.open(image_path).convert("RGB")
        img_pil_preprocessed_rot, _ = rotate_to_wide(original_pil_img.copy())
        img_pil_padded_for_overlay, _, _, scale_factor_applied = rescale_and_pad_image(img_pil_preprocessed_rot, TARGET_SIZE)
        
        eleven_channel_data_np = create_11channel_input(
            img_pil_padded_for_overlay, SATO_SIGMAS, MEIJERING_SIGMAS, FRANGI_SIGMAS, HESSIAN_SIGMAS, ENHANCE_PERCENTILE
        )
        input_tensor = torch.from_numpy(eleven_channel_data_np).permute(2, 0, 1).float().unsqueeze(0).to(device)
        
        return input_tensor, img_pil_padded_for_overlay
    except Exception as e:
        print(f"Error during preprocessing of {image_path}: {e}")
        return None, None

def perform_prediction(model, input_tensor):
    """
    Performs inference on the input tensor using the loaded model.
    Returns the predicted segmentation mask (numpy array) and geodesic map (tensor, not processed to numpy here).
    """
    with torch.no_grad():
        seg_outputs, geo_outputs = model(input_tensor)
        predicted_mask = torch.argmax(F.softmax(seg_outputs, dim=1), dim=1).squeeze(0).cpu().numpy()
        # You can process geo_outputs here if you want to save them as images as well
        # predicted_geodesic_map = geo_outputs.squeeze(0).cpu().numpy()
        return predicted_mask, geo_outputs # Return geo_outputs as is for now

def save_prediction_outputs(output_dir, original_pil_image, predicted_mask, original_filename_stem):
    """
    Saves the predicted segmentation mask and the overlay image to the specified directory.
    """
    # Create mask image (0, 1, 2 values)
    mask_img = Image.fromarray(predicted_mask.astype(np.uint8), mode='L')
    mask_img_path = output_dir / f"{original_filename_stem}_mask.png"
    mask_img.save(mask_img_path)

    # Create and save RGB overlay
    base_image_rgba = original_pil_image.convert("RGBA")
    overlay = Image.new('RGBA', TARGET_SIZE, (0, 0, 0, 0))

    overlay = draw_mask_on_overlay(overlay, predicted_mask, BLADE_COLOR, 1) # Blade (Class 1)
